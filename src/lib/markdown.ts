import { unified } from 'unified'
import remarkParse from 'remark-parse'
import remarkGfm from 'remark-gfm'
import remarkMath from 'remark-math'
import remarkRehype from 'remark-rehype'
import rehypeRaw from 'rehype-raw'
import rehypeSanitize, { defaultSchema, type Options as SanitizeSchema } from 'rehype-sanitize'
import rehypeKatex from 'rehype-katex'
import rehypeHighlight from 'rehype-highlight'
import rehypeStringify from 'rehype-stringify'

// GitHub's sanitize schema, plus the classes remark-math puts on math nodes so
// rehype-katex can still find them after sanitizing.
const schema: SanitizeSchema = {
  ...defaultSchema,
  attributes: {
    ...defaultSchema.attributes,
    code: [
      ...(defaultSchema.attributes?.code ?? []),
      ['className', /^language-./, 'math-inline', 'math-display'],
    ],
  },
}

// Sanitize runs before KaTeX and highlighting: user-written HTML is cleaned,
// while markup generated by the later plugins is trusted.
const processor = unified()
  .use(remarkParse)
  .use(remarkGfm)
  .use(remarkMath)
  .use(remarkRehype, { allowDangerousHtml: true })
  .use(rehypeRaw)
  .use(rehypeSanitize, schema)
  .use(rehypeKatex, { strict: 'ignore' })
  .use(rehypeHighlight, { plainText: ['mermaid'] })
  .use(rehypeStringify)

export function renderMarkdown(markdown: string): string {
  return String(processor.processSync(markdown))
}
